// Installed-asset integration for actual Button/Input/ChoiceList/geometry hooks.
import assert from 'node:assert/strict';
import test from 'node:test';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {readFile,mkdtemp} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {fileURLToPath} from 'node:url';
const run=promisify(execFile),root=fileURLToPath(new URL('../../../',import.meta.url));
const enabled=Boolean(process.env.SMAC_ASSETS_DIR&&process.env.WASM_APP_DIR);

test('actual native controls publish value, transformed label, typed choices, ownership and inherited geometry',{skip:!enabled,timeout:150000},async()=>{
 const artifacts=await mkdtemp(`${tmpdir()}/presentation-native-controls-`);
 const executed=await run(process.execPath,['tools/behavior-tests/state_trace/presentation_intro_browser.mjs'],{cwd:root,env:{...process.env,PRESENTATION_ARTIFACTS:artifacts,PRESENTATION_CONTROL_PROBE:'1'},timeout:140000,maxBuffer:16*1024*1024});
 const response=JSON.parse(executed.stdout);assert.equal(response.failure,null);
 const capture=JSON.parse(await readFile(`${artifacts}/presentation-raw.json`,'utf8'));
 const raw=capture.batches.flatMap(batch=>batch.events);
 assert.ok(raw.some(e=>e.kind==='semantic.protocol'&&e.data.version===2),'runtime contains required v2 producer');
 const code="import json,sys;from pathlib import Path;sys.path.insert(0,'tools/behavior-tests');from state_trace.presentation_projector import project_capture;from state_trace.presentation_audit import audit_capture;cases=json.loads(Path('tools/behavior-tests/state_trace/presentation-cases.json').read_text())['cases'];case=next(c for c in cases if c['id']=='presentation-intro-launch');capture=json.loads(Path(sys.argv[1]).read_text());projection=project_capture(capture,case['input']);Path(sys.argv[2]).write_text(json.dumps(projection));Path(sys.argv[2]).with_name('audit.json').write_text(json.dumps(audit_capture(capture,projection)))";
 await run(process.env.PYTHON||'python3',['-c',code,`${artifacts}/presentation-raw.json`,`${artifacts}/semantic.json`],{cwd:root,timeout:20000,maxBuffer:16*1024*1024});
 const output=JSON.parse(await readFile(`${artifacts}/semantic.json`,'utf8'));
 const state=output.checkpoints.at(-1).state.presentation;
 const find=source=>Object.entries(state.objects).find(([,obj])=>obj.source===source);
 const [buttonId,button]=find('native-control-fixture.button');
 const [editorId,editor]=find('native-control-fixture.editor');
 const [choicesId,choices]=find('native-control-fixture.choices');
 assert.equal(button.text,'MIXED LABEL');assert.equal(editor.value,'ABCz');assert.equal(editor.max_length,12);
 const [,capped]=find('native-control-fixture.capped'),[,empty]=find('native-control-fixture.empty');
 assert.match(await readFile(`${artifacts}/application.log`,'utf8'),/PRESENTATION_NATIVE_CAPPED_VALUE\|ABC(?:\r?\n|$)/,'real Input event submits the capped native value');
 assert.equal(capped.value,'ABC','stored request ABCD must not replace unchanged actual capped value');
 assert.equal(capped.max_length,3);
 assert.equal(empty.value,'','new empty editor has an actual native-state baseline');
 assert.equal(empty.max_length,0);
 assert.equal(editor.text,null,'cursor paint is not an editor human label');
 assert.deepEqual(choices.items.map(item=>[item.key,item.label]),[['beta','Same label'],['gamma','Same label']]);
 assert.equal(choices.selected,'gamma');
 assert.ok(choices.items.every(item=>state.objects[item.control]?.parent===choicesId));
 const nativeId=id=>id.replace('candidate-birth:','');
 const mappings=Object.entries(output.diagnostics.dispositions);
 const label=mappings.find(([,record])=>record.mapping?.owner===nativeId(buttonId)&&record.mapping.relation==='label');
 const audio=mappings.find(([,record])=>record.mapping?.owner===nativeId(buttonId)&&record.mapping.relation==='audio-support');
 const display=mappings.find(([,record])=>record.mapping?.owner===nativeId(editorId)&&record.mapping.relation==='editor-display');
 const [selectId]=find('native-control-fixture.select');
 const popup=mappings.find(([,record])=>record.mapping?.owner===nativeId(selectId)&&record.mapping.relation==='choice-popup');
 assert.ok(popup,'actual Select constructor declares exact choice-popup ownership');
 const popupId='candidate-birth:'+popup[0],popupControl=state.objects[popupId];
 assert.equal(popupControl.role,'choice-list');assert.equal(popupControl.parent,selectId);
 assert.deepEqual(popupControl.items.map(item=>[item.key,item.label]),[['one','Same select label'],['two','Same select label']]);
 assert.equal(popupControl.selected,'two');
 assert.ok(popupControl.items.every(item=>state.objects[item.control]?.parent===popupId));
 assert.ok(label&&audio&&display,'native members have exact ownership');
 assert.equal(state.objects['candidate-birth:'+label[0]],undefined,'embedded label is not a second control');
 assert.ok(raw.some(e=>e.target===display[0]&&e.kind==='node.property'&&e.data.key==='rendered_text'&&e.data.value==='ABCz_'));
 const geometry=raw.filter(e=>e.target===nativeId(editorId)&&e.kind==='semantic.geometry'&&e.data.area==='layout');
 assert.ok(new Set(geometry.map(e=>e.data.left)).size>=2,'parent movement updates actual child geometry without child property assignment');
 const paragraphs=Object.values(state.objects).filter(obj=>obj.role==='paragraph');
 assert.ok(paragraphs.some(obj=>obj.text==='Actual source paragraph for native layout fragments'));
 assert.ok(mappings.some(([,record])=>record.mapping?.relation==='layout-fragment'));
 assert.ok(mappings.some(([,record])=>record.disposition==='unknown'&&record.retirement_sequence!==null),'unknown transients survive');
 assert.equal(output.diagnostics.observed_events,raw.length);
 const audit=JSON.parse(await readFile(`${artifacts}/audit.json`,'utf8'));
 assert.equal(audit.valid,true);assert.equal(audit.transport_complete,true);
 assert.equal(audit.exhaustive_coverage_complete,false);assert.equal(audit.rendered_output_observed,false);
 assert.equal(Object.keys(audit.coverage).length,15);
 assert.ok(Object.values(audit.coverage).every(channel=>channel.complete===false&&channel.missing_capability_reasons.length>0));
 assert.equal(audit.tail.raw_prefix_event_count,raw.length);
 assert.equal(audit.checkpoints.length,capture.input_checkpoints.length);
 assert.ok(audit.checkpoints.every(point=>point.raw_observations_exactly_once));
 assert.ok(Object.values(audit.unknown_objects).some(object=>object.retirement_sequence!==null),'audit retains unknown retired transients');
 assert.ok(output.checkpoints.every(point=>Object.values(point.coverage).every(value=>value===false)));
 console.log(`Native control artifacts: ${artifacts}`);
});
